func deriveCustomerBillingDates(customer *model.Customer, now time.Time) (time.Time, time.Time) {
	deadlineDay := normalizeCustomerBillingDeadline(customer)
	invoiceDay := normalizedCustomerInvoiceDay(customer, deadlineDay)

	if customer == nil || customer.CurrentInvoice == nil {
		return billing.CurrentCycleDates(now, invoiceDay, deadlineDay)
	}

	if customer.BillingType != "fixed" && customer.CurrentInvoice.Status == "paid" && customer.CurrentInvoice.PaidAt != nil && customer.CurrentInvoice.PaidAt.After(customer.CurrentInvoice.DueDate) {
		deadlineDay = billing.NormalizeDay(customer.CurrentInvoice.PaidAt.Day())
		invoiceDay = billing.InvoiceDayFromDueDay(deadlineDay)
	}

	dueMonth := customer.CurrentInvoice.PeriodMonth
	dueYear := customer.CurrentInvoice.PeriodYear
	if dueMonth <= 0 || dueYear <= 0 {
		return billing.CurrentCycleDates(now, invoiceDay, deadlineDay)
	}

	if customer.CurrentInvoice.Status == "paid" {
		nextCycle := time.Date(dueYear, time.Month(dueMonth), 1, 0, 0, 0, 0, time.UTC).AddDate(0, 1, 0)
		return billing.CycleDates(invoiceDay, deadlineDay, int(nextCycle.Month()), nextCycle.Year())
	}

	invoiceDate, _ := billing.CycleDates(invoiceDay, deadlineDay, dueMonth, dueYear)
	return invoiceDate, customer.CurrentInvoice.DueDate
}

func normalizedCustomerInvoiceDay(customer *model.Customer, deadlineDay int) int {
	if customer == nil {
		return billing.InvoiceDayFromDueDay(deadlineDay)
	}
	if customer.BillingDate > 0 {
		return billing.NormalizeDay(customer.BillingDate)
	}
	return billing.InvoiceDayFromDueDay(deadlineDay)
}

