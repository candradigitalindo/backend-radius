func mapCustomerONT(ont *model.ONT) *customerONTResponse {
	if ont == nil {
		return nil
	}

	resp := &customerONTResponse{
		ID:            ont.ID,
		SerialNumber:  ont.SerialNumber,
		Model:         ont.Model,
		Vendor:        ont.Vendor,
		Status:        ont.Status,
		ProvisionedAt: ont.ProvisionedAt,
		LastOnlineAt:  ont.LastOnlineAt,
		WiFi:          mapCustomerONTWiFi(ont),
		Actions:       ont.Actions,
	}

	if ont.StatusDetail == nil {
		return resp
	}

	resp.Device = mapCustomerONTDevice(ont.StatusDetail)
	resp.Signal = mapCustomerONTSignal(ont.StatusDetail)
	resp.Network = mapCustomerONTNetwork(ont.StatusDetail)
	resp.ConnectedHosts = mapCustomerONTConnectedHosts(ont.StatusDetail)

	return resp
}

func mapCustomerONTDevice(detail *model.ONTStatusDetail) *customerONTDeviceResponse {
	if detail == nil {
		return nil
	}
	if detail.DeviceID == "" && detail.SoftwareVersion == "" && detail.LastInform == "" && detail.Uptime == nil && !detail.DataRealtime {
		return nil
	}

	return &customerONTDeviceResponse{
		DeviceID:        detail.DeviceID,
		SoftwareVersion: detail.SoftwareVersion,
		LastInform:      detail.LastInform,
		DataRealtime:    detail.DataRealtime,
		Uptime:          detail.Uptime,
	}
}

func mapCustomerONTSignal(detail *model.ONTStatusDetail) *customerONTSignalResponse {
	if detail == nil {
		return nil
	}
	if detail.RxPower == nil && detail.TxPower == nil {
		return nil
	}

	return &customerONTSignalResponse{
		RxPower: detail.RxPower,
		TxPower: detail.TxPower,
	}
}

func mapCustomerONTWiFi(ont *model.ONT) *customerONTWiFiResponse {
	if ont == nil {
		return nil
	}

	resp := &customerONTWiFiResponse{}
	if detail := ont.StatusDetail; detail != nil {
		resp.SSID = detail.WiFiSSID
		resp.Password = detail.WiFiPassword
		resp.PasswordReported = detail.WiFiPasswordReported
		resp.PasswordSource = detail.WiFiPasswordSource
		resp.Security = detail.WiFiSecurity
		resp.SecurityModes = detail.WiFiSecurityModes
	}

	if resp.SSID == "" && ont.LastKnownWiFiSSID != nil {
		resp.SSID = *ont.LastKnownWiFiSSID
	}
	if resp.Password == "" && ont.LastKnownWiFiPassword != nil {
		resp.Password = *ont.LastKnownWiFiPassword
	}
	if resp.PasswordSource == "" && ont.LastKnownWiFiSource != nil && *ont.LastKnownWiFiSource != "" {
		resp.PasswordSource = normalizeWiFiPasswordSource(*ont.LastKnownWiFiSource)
	}
	if resp.Password == "" {
		resp.PasswordReported = false
	}
	if resp.Security == "" && ont.LastKnownWiFiSecurity != nil {
		resp.Security = *ont.LastKnownWiFiSecurity
	}

	return resp
}

func normalizeWiFiPasswordSource(source string) string {
	switch source {
	case "", "set_request":
		return "last_sent"
	default:
		return source
	}
}

