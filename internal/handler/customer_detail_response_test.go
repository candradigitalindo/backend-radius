func TestNewCustomerDetailResponseFallsBackToCachedWiFi(t *testing.T) {
	ssid := "BINJAI-NET"
	password := "rahasia123"
	security := "11i"
	source := "set_request"

	resp := newCustomerDetailResponse(&model.Customer{
		ID:       "cust-2",
		TenantID: "tenant-1",
		Name:     "Pelanggan",
		ONT: &model.ONT{
			ID:                    "ont-2",
			SerialNumber:          "HWTC0002",
			Status:                "active",
			LastKnownWiFiSSID:     &ssid,
			LastKnownWiFiPassword: &password,
			LastKnownWiFiSecurity: &security,
			LastKnownWiFiSource:   &source,
		},
	})

	encoded, err := json.Marshal(resp)
	if err != nil {
		t.Fatalf("marshal response: %v", err)
	}

	var payload map[string]any
	if err := json.Unmarshal(encoded, &payload); err != nil {
		t.Fatalf("unmarshal payload: %v", err)
	}

	ontPayload := payload["ont"].(map[string]any)
	wifiPayload := ontPayload["wifi"].(map[string]any)
	if got := wifiPayload["ssid"]; got != ssid {
		t.Fatalf("unexpected cached ssid: %v", got)
	}
	if got := wifiPayload["password"]; got != password {
		t.Fatalf("unexpected cached password: %v", got)
	}
	if got := wifiPayload["password_source"]; got != "last_sent" {
		t.Fatalf("unexpected password source: %v", got)
	}
	if got := wifiPayload["password_reported"]; got != false {
		t.Fatalf("cached password must not be marked as device-reported: %v", got)
	}
}

