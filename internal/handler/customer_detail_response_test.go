func TestMapCustomerBillingUsesExplicitInvoiceAndDueDates(t *testing.T) {
	now := time.Date(2026, time.May, 24, 8, 0, 0, 0, time.UTC)
	billing := mapCustomerBilling(&model.Customer{
		JoinDate:        time.Date(2026, time.January, 1, 0, 0, 0, 0, time.UTC),
		BillingDate:     24,
		BillingType:     "fixed",
		BillingDeadline: 1,
	}, now)

	wantInvoiceDate := time.Date(2026, time.May, 24, 0, 0, 0, 0, time.UTC)
	wantDueDate := time.Date(2026, time.June, 1, 0, 0, 0, 0, time.UTC)
	if billing.InvoiceDate == nil || !billing.InvoiceDate.Equal(wantInvoiceDate) {
		t.Fatalf("billing.InvoiceDate = %v, want %v", billing.InvoiceDate, wantInvoiceDate)
	}
	if billing.BillingDueDate == nil || !billing.BillingDueDate.Equal(wantDueDate) {
		t.Fatalf("billing.BillingDueDate = %v, want %v", billing.BillingDueDate, wantDueDate)
	}
}

func TestMapCustomerBillingShowsNextCycleWhenLatestInvoicePaid(t *testing.T) {
	now := time.Date(2026, time.May, 25, 8, 0, 0, 0, time.UTC)
	paidAt := time.Date(2026, time.May, 25, 9, 0, 0, 0, time.UTC)
	billing := mapCustomerBilling(&model.Customer{
		JoinDate:        time.Date(2026, time.January, 1, 0, 0, 0, 0, time.UTC),
		BillingDate:     24,
		BillingType:     "fixed",
		BillingDeadline: 1,
		CurrentInvoice: &model.Invoice{
			PeriodMonth: 6,
			PeriodYear:  2026,
			Status:      "paid",
			DueDate:     time.Date(2026, time.June, 1, 0, 0, 0, 0, time.UTC),
			PaidAt:      &paidAt,
		},
	}, now)

	wantInvoiceDate := time.Date(2026, time.June, 24, 0, 0, 0, 0, time.UTC)
	wantDueDate := time.Date(2026, time.July, 1, 0, 0, 0, 0, time.UTC)
	if billing.InvoiceDate == nil || !billing.InvoiceDate.Equal(wantInvoiceDate) {
		t.Fatalf("billing.InvoiceDate = %v, want %v", billing.InvoiceDate, wantInvoiceDate)
	}
	if billing.BillingDueDate == nil || !billing.BillingDueDate.Equal(wantDueDate) {
		t.Fatalf("billing.BillingDueDate = %v, want %v", billing.BillingDueDate, wantDueDate)
	}
}

